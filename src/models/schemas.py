"""Shared Pydantic Data Contracts for SentinelForge.

Description: Central data models defining all payloads flowing across agents,
             HITL confirmation gates, and MCP servers.
Need: A single source of truth for pipeline inputs/outputs avoids contract
      drift between specialist agents.
Motive: Provide strongly typed, validated representations for Analysis, Specs,
        Costs, Infra, Code Diffs, and Security Audits.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class StepStatus(str, Enum):
    """Execution status for pipeline steps and gates."""
    PENDING = "PENDING"
    WAITING_APPROVAL = "WAITING_APPROVAL"
    IN_PROGRESS = "IN_PROGRESS"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"


class WorkloadSpec(BaseModel):
    """Standardized technical specifications of a software workload."""
    name: str = Field(description="Workload or application service name")
    cpu_cores: float = Field(default=1.0, description="Allocated or estimated CPU cores")
    ram_gb: float = Field(default=2.0, description="Allocated or estimated RAM in Gigabytes")
    disk_gb: float = Field(default=10.0, description="Allocated disk storage in Gigabytes")
    monthly_requests: int = Field(default=100000, description="Estimated monthly HTTP/RPC requests")
    is_stateful: bool = Field(default=False, description="Whether the service maintains local persistent state/session")


class AnalysisResult(BaseModel):
    """Output generated by AnalysisAgent from inspecting a legacy codebase or repository."""
    detected_platform: str = Field(
        default="Unknown",
        description="Detected current hosting platform (e.g., GCE, GKE, CloudRun, BareMetal)"
    )
    workload_spec: WorkloadSpec = Field(
        description="Extracted/estimated resource requirements and workload profile"
    )
    summary: str = Field(
        description="Natural language summary of the analyzed application and architecture"
    )
    files_of_interest: List[str] = Field(
        default_factory=list,
        description="Key application files, entry points, and deployment configurations discovered"
    )
    architecture_type: str = Field(
        default="Unknown",
        description="Classified architectural style (e.g., Stateless API, Stateful Monolith, Microservice)"
    )
    framework: str = Field(
        default="Unknown",
        description="Detected web/application framework (e.g., Flask, FastAPI, Django, Express, Spring)"
    )
    dependencies: List[str] = Field(
        default_factory=list,
        description="Key package dependencies identified in the codebase"
    )
    has_dockerfile: bool = Field(
        default=False,
        description="Whether a container build specification was found"
    )
    has_autoscaling: bool = Field(
        default=False,
        description="Whether autoscaling mechanisms were detected in deploy configs"
    )
    graph_summary: Dict[str, Any] = Field(
        default_factory=dict,
        description="GraphRAG knowledge graph statistics (nodes, edges, call hierarchy, routes)"
    )
    recommendations: List[str] = Field(
        default_factory=list,
        description="Target modernization recommendations (e.g. migrate to Cloud Run, containerize)"
    )


class SpecResult(BaseModel):
    """Output generated by SpecAgent when formulating API contracts from concepts/ideas."""
    spec_type: str = Field(
        default="OpenAPI",
        description="Specification format type (e.g., OpenAPI, AsyncAPI, Protobuf)"
    )
    title: str = Field(default="", description="API/Service title")
    version: str = Field(default="1.0.0", description="API version")
    summary: str = Field(
        default="",
        description="Executive summary of the generated service specification"
    )
    raw_spec: str = Field(
        default="",
        description="Raw specification text (YAML or JSON schema representation)"
    )
    parsed_spec: Dict[str, Any] = Field(
        default_factory=dict,
        description="Parsed specification document structure"
    )
    workload_spec: Optional[WorkloadSpec] = Field(
        default=None,
        description="Derived WorkloadSpec for sizing and downstream cost estimation"
    )
    endpoints: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of defined endpoints, HTTP methods, and summaries"
    )
    data_models: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of defined data models / Pydantic schema schemas"
    )


class CostEstimate(BaseModel):
    """Estimated monthly GCP infrastructure cost for a specific hosting platform."""
    platform: str = Field(description="Target platform: GCE, GKE, or CloudRun")
    monthly_cost_usd: float = Field(description="Total estimated monthly cost in USD")
    breakdown: Dict[str, float] = Field(
        default_factory=dict,
        description="Cost breakdown across compute, memory, storage, and networking"
    )


class MigrationPlan(BaseModel):
    """Proposal comparing baseline vs target platform architecture, cost, and savings."""
    baseline: CostEstimate = Field(description="Current baseline platform cost estimate")
    target: CostEstimate = Field(description="Recommended target platform cost estimate")
    target_platform: str = Field(description="Recommended target GCP platform")
    monthly_savings_usd: float = Field(description="Projected monthly savings in USD")
    savings_pct: float = Field(description="Percentage cost reduction")
    rationale: str = Field(description="Architectural rationale for the recommendation")


class CodeDiff(BaseModel):
    """Git commit and file diff produced during code refactoring or generation."""
    branch_name: str = Field(description="Git branch where code changes were authored")
    files_changed: List[str] = Field(
        default_factory=list,
        description="List of file paths modified or created"
    )
    diff_text: str = Field(description="Unified git diff representation of code changes")
    unit_tests_added: List[str] = Field(
        default_factory=list,
        description="Names of unit test cases added or updated"
    )


class InfraArtifacts(BaseModel):
    """Infrastructure-as-Code and CI/CD artifacts generated for target platform."""
    main_tf: str = Field(default="", description="Rendered Terraform HCL configuration")
    service_yaml: str = Field(default="", description="Rendered Cloud Run / Kubernetes YAML manifest")
    cloudbuild_yaml: str = Field(default="", description="Rendered Cloud Build CI/CD pipeline YAML")
    validation_passed: bool = Field(default=True, description="Whether syntax validation passed")
    validation_findings: List[str] = Field(
        default_factory=list,
        description="Linter, syntax validator, or security policy findings"
    )


class AuditReport(BaseModel):
    """Security pentest & vulnerability findings report from Strix/DAST scanners."""
    target_url: str = Field(description="Target URL or endpoint evaluated")
    vulnerabilities_found: int = Field(default=0, description="Total vulnerability count")
    critical_count: int = Field(default=0, description="Number of critical vulnerabilities")
    findings: List[str] = Field(
        default_factory=list,
        description="Detailed list of CVSS findings and remediation guidance"
    )


class GateDecision(BaseModel):
    """Human-in-the-Loop Gate approval or rejection decision."""
    step_id: int = Field(description="ID of the confirmation gate (1 to 5)")
    approved: bool = Field(description="Whether the gate was approved by the human operator")
    feedback: Optional[str] = Field(
        default=None,
        description="Optional reviewer feedback, adjustments, or rejection reason"
    )
